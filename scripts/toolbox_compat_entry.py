"""Build the in-wardrobe Toolbox entry from the standalone page sources.

AstrBot page asset tickets are page-scoped and the frame cannot navigate its
parent. Keeping this entry under wardrobe lets ordinary links retain both the
ticket scope and the existing authenticated bridge, without changing AstrBot.
"""
from pathlib import Path
import shutil


def render_entry(source):
    marker = '<div class="hero-tools">'
    if source.count(marker) != 1:
        raise ValueError('Standalone Toolbox header changed; update compatibility entry')
    return ('<!-- Generated by scripts/toolbox_compat_entry.py; edit the standalone source. -->\n'
            + source.replace(marker, marker + '<a id="return-wardrobe" class="return-link" href="../index.html">← 返回服装词库</a>', 1))


def sync(root):
    source = root / 'pages/wardrobe_toolbox'
    target = root / 'pages/wardrobe/toolbox'
    target.mkdir(parents=True, exist_ok=True)
    (target/'index.html').write_text(render_entry((source/'index.html').read_text(encoding='utf-8')), encoding='utf-8')
    for name in ('app.js', 'style.css'):
        shutil.copyfile(source/name, target/name)


if __name__ == '__main__':
    sync(Path(__file__).resolve().parents[1])
